def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    workbook = xlsxwriter.Workbook(str(OUTPUT))
    sheet = workbook.add_worksheet("Стадии и этапы")

    headers = [
        "Стадия разработки",
        "Этап работ",
        "Содержание работ",
        "Сроки выполнения",
        "Исполнители",
    ]

    title_fmt = workbook.add_format(
        {
            "bold": True,
            "font_size": 14,
            "align": "center",
            "valign": "vcenter",
        }
    )
    header_fmt = workbook.add_format(
        {
            "bold": True,
            "text_wrap": True,
            "align": "center",
            "valign": "vcenter",
            "border": 1,
            "bg_color": "#D9EAF7",
        }
    )
    cell_fmt = workbook.add_format(
        {
            "text_wrap": True,
            "valign": "top",
            "border": 1,
        }
    )
    centered_fmt = workbook.add_format(
        {
            "text_wrap": True,
            "valign": "top",
            "align": "center",
            "border": 1,
        }
    )

    sheet.merge_range(0, 0, 0, 4, "Таблица 2 - Стадии и этапы разработки", title_fmt)

    for col, header in enumerate(headers):
        sheet.write(2, col, header, header_fmt)

    for row_idx, row in enumerate(ROWS, start=3):
        for col_idx, value in enumerate(row):
            fmt = cell_fmt
            if col_idx in (0, 1, 3, 4):
                fmt = centered_fmt
            sheet.write(row_idx, col_idx, value, fmt)

    sheet.set_column("A:A", 24)
    sheet.set_column("B:B", 40)
    sheet.set_column("C:C", 82)
    sheet.set_column("D:D", 20)
    sheet.set_column("E:E", 28)

    sheet.set_row(0, 24)
    sheet.set_row(2, 34)
    for idx in range(3, 3 + len(ROWS)):
        sheet.set_row(idx, 60)

    sheet.freeze_panes(3, 0)

    workbook.close()
    print(OUTPUT)


if __name__ == "__main__":
    main()
